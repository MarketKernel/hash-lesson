// Шаг 17: семнадцать шагов x = x² + m. Алгебра ещё работает, но уже ~16 с.

import { polynomials } from "./algebra.ts";

export const P = 786433; // простое число, чуть меньше 2²⁰

export function hash(m: number): number {
  let x = (m * m + m) % P; // шаг 1
  x = (x * x + m) % P; // шаг 2
  x = (x * x + m) % P; // шаг 3
  x = (x * x + m) % P; // шаг 4
  x = (x * x + m) % P; // шаг 5
  x = (x * x + m) % P; // шаг 6
  x = (x * x + m) % P; // шаг 7
  x = (x * x + m) % P; // шаг 8
  x = (x * x + m) % P; // шаг 9
  x = (x * x + m) % P; // шаг 10
  x = (x * x + m) % P; // шаг 11
  x = (x * x + m) % P; // шаг 12
  x = (x * x + m) % P; // шаг 13
  x = (x * x + m) % P; // шаг 14
  x = (x * x + m) % P; // шаг 15
  x = (x * x + m) % P; // шаг 16
  x = (x * x + m) % P; // шаг 17
  //
  // То же одной формулой — подставили каждый шаг в следующий и раскрыли скобки:
  //
  //   x = (m ** 131072
  //      + 65536 * m ** 131071
  //      + 2147450880 * m ** 131070
  //      + …                     ← здесь ещё около 131 тысячи слагаемых
  //      + 5 * m ** 4
  //      + 2 * m ** 3
  //      + m ** 2
  //      + m) % P;
  //
  // Это многочлен степени 2¹⁷ = 131 072 — пока меньше P.
  // Коэффициенты в середине огромные: их сумма — число из 23 189 цифр.
  return x;
}

// Обратная: по h найти какое-нибудь m, у которого hash(m) = h (или null, если такого нет).
//
// Тот же алгоритм, что в шаге 2 (findRoot в algebra.ts): ищем корень многочлена f(m) − h.
// Отличие одно: 131 072 коэффициента в код руками не вписать, поэтому многочлен строим программой —
// теми же шагами, что и hash, только не над числом x, а над многочленом f:  f = f² + m.
//
// Замер: ~16 с. Каждый шаг удваивает степень, и время растёт примерно вдвое. Подробнее — README.md.
// progress (необязательно) получает долю сделанной работы от 0 до 1 — для показа процентов.
const { add, mul, findRoot } = polynomials(P);

export function invert(h: number, progress?: (done: number) => void): number | null {
  const M = [0, 1]; // многочлен «m»
  let f = [0, 1, 1]; // шаг 1: m² + m
  f = add(mul(f, f), M); // шаг 2
  f = add(mul(f, f), M); // шаг 3
  f = add(mul(f, f), M); // шаг 4
  f = add(mul(f, f), M); // шаг 5
  f = add(mul(f, f), M); // шаг 6
  f = add(mul(f, f), M); // шаг 7
  f = add(mul(f, f), M); // шаг 8
  f = add(mul(f, f), M); // шаг 9
  f = add(mul(f, f), M); // шаг 10
  f = add(mul(f, f), M); // шаг 11
  f = add(mul(f, f), M); // шаг 12
  f = add(mul(f, f), M); // шаг 13
  f = add(mul(f, f), M); // шаг 14
  f = add(mul(f, f), M); // шаг 15
  f = add(mul(f, f), M); // шаг 16
  f = add(mul(f, f), M); // шаг 17
  return findRoot(add(f, [-h]), progress); // корень f(m) − h
}
