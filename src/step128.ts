// Алгоритм из шагов 2–25 (findRoot в algebra.ts) стоил бы ~P · log² P ≈ 2¹⁴² операций —
// по оценке из README.md ~10²⁸ лет и ~10²⁹ ТБ памяти. Других известных способов быстрее ~P нет.
