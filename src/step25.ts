// Шаг 25: двадцать пять шагов x = x² + m. Алгебра упирается в P: ~2 минуты.

import { polynomials } from "./algebra.ts";

export const P = 786433; // простое число, чуть меньше 2²⁰

export function hash(m: number): number {
  let x = (m * m + m) % P; // шаг 1
  x = (x * x + m) % P; // шаг 2
  x = (x * x + m) % P; // шаг 3
  x = (x * x + m) % P; // шаг 4
  x = (x * x + m) % P; // шаг 5
  x = (x * x + m) % P; // шаг 6
  x = (x * x + m) % P; // шаг 7
  x = (x * x + m) % P; // шаг 8
  x = (x * x + m) % P; // шаг 9
  x = (x * x + m) % P; // шаг 10
  x = (x * x + m) % P; // шаг 11
  x = (x * x + m) % P; // шаг 12
  x = (x * x + m) % P; // шаг 13
  x = (x * x + m) % P; // шаг 14
  x = (x * x + m) % P; // шаг 15
  x = (x * x + m) % P; // шаг 16
  x = (x * x + m) % P; // шаг 17
  x = (x * x + m) % P; // шаг 18
  x = (x * x + m) % P; // шаг 19
  x = (x * x + m) % P; // шаг 20
  x = (x * x + m) % P; // шаг 21
  x = (x * x + m) % P; // шаг 22
  x = (x * x + m) % P; // шаг 23
  x = (x * x + m) % P; // шаг 24
  x = (x * x + m) % P; // шаг 25
  //
  // То же одной формулой — подставили каждый шаг в следующий и раскрыли скобки:
  //
  //   x = (m ** 33554432
  //      + 16777216 * m ** 33554431
  //      + 140737479966720 * m ** 33554430
  //      + …                     ← здесь ещё больше 33 миллионов слагаемых
  //      + 5 * m ** 4
  //      + 2 * m ** 3
  //      + m ** 2
  //      + m) % P;
  //
  // Это многочлен степени 2²⁵ = 33 554 432 — больше P.
  // Коэффициенты в середине огромные: одна их сумма — число из 5 936 176 цифр.
  // Без раскрытия скобок не лучше: строка подстановки удваивается с каждым шагом —
  // после 25 шагов в ней около 537 миллионов символов.
  return x;
}

// Обратная: по h найти какое-нибудь m, у которого hash(m) = h (или null, если такого нет).
//
// 1. Размотать назад нельзя. Шаг назад x = √(h − m) требует m, а его мы и ищем.
//
// 2. Формулы нет. Обратная — это решение уравнения
//      m ** 33554432 + 16777216 * m ** 33554431 + … + m − h = 0   (mod P)
//    Готовой формулы, как школьная для 2-й степени (шаг 1), нет уже для 5-й степени.
//
// 3. Остаётся алгоритм из шагов 2 и 17 (findRoot в algebra.ts). Многочлен строим теми же шагами,
//    что и hash: f = f² + m. Но степень 2²⁵ = 33 миллиона не поместится в память — поэтому после
//    каждого шага урезаем его по теореме Ферма (m^P = m): m^k при k ≥ P заменяем на m^(k−P+1).
//    Значения многочлена от этого не меняются — значит, и корни те же. Степень остаётся меньше P.
//
// 4. Меньше P урезать уже нельзя: в многочлене ~P слагаемых, и любой метод, который с ним работает,
//    тратит на каждое хотя бы по операции. Цена — ~P · log² P.
//    Замер: ~2 минуты (построить многочлен — 8 с, m^P — 6 с, НОД — 106 с).
//
// При P ≈ 2²⁵⁶ — то же самое, только ~P — это уже 2²⁵⁶: столько операций не сделать никогда.
//
// progress (необязательно) получает долю сделанной работы от 0 до 1 — для показа процентов.
const { add, mul, fermat, findRoot } = polynomials(P);

export function invert(h: number, progress?: (done: number) => void): number | null {
  const M = [0, 1]; // многочлен «m»
  let f = [0, 1, 1]; // шаг 1: m² + m
  f = fermat(add(mul(f, f), M)); // шаг 2
  f = fermat(add(mul(f, f), M)); // шаг 3
  f = fermat(add(mul(f, f), M)); // шаг 4
  f = fermat(add(mul(f, f), M)); // шаг 5
  f = fermat(add(mul(f, f), M)); // шаг 6
  f = fermat(add(mul(f, f), M)); // шаг 7
  f = fermat(add(mul(f, f), M)); // шаг 8
  f = fermat(add(mul(f, f), M)); // шаг 9
  f = fermat(add(mul(f, f), M)); // шаг 10
  f = fermat(add(mul(f, f), M)); // шаг 11
  f = fermat(add(mul(f, f), M)); // шаг 12
  f = fermat(add(mul(f, f), M)); // шаг 13
  f = fermat(add(mul(f, f), M)); // шаг 14
  f = fermat(add(mul(f, f), M)); // шаг 15
  f = fermat(add(mul(f, f), M)); // шаг 16
  f = fermat(add(mul(f, f), M)); // шаг 17
  f = fermat(add(mul(f, f), M)); // шаг 18
  f = fermat(add(mul(f, f), M)); // шаг 19
  f = fermat(add(mul(f, f), M)); // шаг 20
  f = fermat(add(mul(f, f), M)); // шаг 21
  f = fermat(add(mul(f, f), M)); // шаг 22
  f = fermat(add(mul(f, f), M)); // шаг 23
  f = fermat(add(mul(f, f), M)); // шаг 24
  f = fermat(add(mul(f, f), M)); // шаг 25
  return findRoot(add(f, [-h]), progress); // корень f(m) − h
}
