// Шаг 1: один шаг x = x² + m.

export const P = 786433; // то же P, что в остальных шагах (формула работает для любого простого, кроме 2)

export function hash(m: number): number {
  return (m * m + m) % P; // шаг 1
}

// Обратная: по h найти какое-нибудь m, у которого hash(m) = h (или null, если такого нет).
// Это квадратное уравнение m² + m − h = 0, решаем по школьной формуле:
//   m = (−1 + √D) / 2,   D = 1 + 4h.
// По модулю P:
//   −1 = P − 1;
//   делить на 2 = умножать на (P+1)/2, потому что 2 · (P+1)/2 = P + 1 = 1;
//   √D — своим алгоритмом, см. sqrt ниже.
export function invert(h: number): number | null {
  const D = (1 + 4 * h) % P;
  const s = sqrt(D);
  if (s === null) return null; // D не квадрат — решений нет
  return ((P - 1 + s) * ((P + 1) / 2)) % P; // (−1 + √D) / 2
}

// Квадратный корень по модулю P — алгоритм Чиполлы. Работает для любого простого P.
//
// Квадратами являются ровно половина ненулевых чисел. Отличить их помогает критерий Эйлера:
//   a^((P−1)/2) = 1, если a — квадрат, и = −1 (то есть P − 1), если нет.
//
// Дальше — как с комплексными числами. Находим t, для которого w = t² − a НЕ квадрат,
// и вводим «мнимое» число i с i² = w (как i² = −1 у комплексных). Числа теперь — пары x + y·i.
// Тогда √a = (t + i)^((P+1)/2), и результат оказывается обычным числом (y = 0).
function sqrt(a: number): number | null {
  if (a === 0) return 0;
  if (powMod(a, (P - 1) / 2) !== 1) return null; // a не квадрат — корня нет

  let t = 0;
  while (powMod((t * t - a + P * P) % P, (P - 1) / 2) !== P - 1) t++; // ищем t: t² − a не квадрат
  const w = (t * t - a + P * P) % P; // i² = w

  // (x₁ + y₁·i)(x₂ + y₂·i) = (x₁x₂ + y₁y₂·w) + (x₁y₂ + y₁x₂)·i
  const mul = ([x1, y1]: number[], [x2, y2]: number[]): number[] => [
    (x1 * x2 + ((y1 * y2) % P) * w) % P,
    (x1 * y2 + y1 * x2) % P,
  ];

  // (t + i)^((P+1)/2) — возведение в степень через квадраты, как в powMod
  let r = [1, 0];
  let b = [t, 1];
  for (let e = (P + 1) / 2; e > 0; e = Math.floor(e / 2)) {
    if (e % 2) r = mul(r, b);
    b = mul(b, b);
  }
  return r[0];
}

/** b^e по модулю P — через возведение в квадрат. */
function powMod(b: number, e: number): number {
  let r = 1;
  for (; e > 0; e = Math.floor(e / 2)) {
    if (e % 2) r = (r * b) % P;
    b = (b * b) % P;
  }
  return r;
}
